from arc_runner import observation as OBS


def trusted_addition_batch_runner():
    @lru_cache(maxsize=512)
    def grade(text, entries):
        try:
            tree = ast.parse(text)
        except SyntaxError:
            return set()
        namespace = {}
        args = ast.dump(ast.parse("def f(x, y): pass").body[0].args)
        addition = ast.dump(ast.parse("x + y", mode="eval").body)
        for node in tree.body:
            if (not isinstance(node, ast.FunctionDef) or node.decorator_list
                    or len(node.body) != 1 or not isinstance(node.body[0], ast.Return)
                    or ast.dump(node.args) != args):
                return set()
            value = node.body[0].value
            if ast.dump(value) == addition:
                namespace[node.name] = lambda x, y: x + y
            elif isinstance(value, ast.Constant) and value.value is None:
                namespace[node.name] = lambda x, y: None
            else:
                return set()
        passed = set()
        for item_id, checks in entries:
            try:
                for check in checks:  # trusted, authored fixture assertions only
                    exec(check, dict(namespace))
                passed.add(item_id)
            except Exception:
                pass
        return passed
    def run(text, items):
        return set(grade(text, tuple((i.id, tuple(i.checks)) for i in items)))
    return custody.attest_exact_check(run)


