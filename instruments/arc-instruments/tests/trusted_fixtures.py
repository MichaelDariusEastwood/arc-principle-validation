"""Test-only stand-ins for an external grader and a reviewed calibration record.

These are neither released instruments nor empirical calibration evidence. The grader accepts only
the tiny addition language generated by this test suite, and never executes submitted Python.
The calibration counts below are invented fixture data for exercising acceptance and refusal paths.
"""
import ast
from functools import lru_cache

from arc_runner import custody
